// Regenerate src/catalog/inventory.generated.ts from the installed
// @napplet/nap type declarations and the pinned NAP documents.
//   node packages/conformance/scripts/generate-inventory.ts
// Needs network access for the NAP documents (raw.githubusercontent.com).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { AUTHORITY, NAP_PACKAGE_VERSION } from '../src/authority.ts';
import { SUPPORTED_DOMAINS } from '../src/catalog/domains.ts';
import { parseNapTypes, parseNapWireFields, parseNapWireTable } from '../src/catalog/nap-types-parser.ts';
import { readPackageFields } from '../src/catalog/nap-type-fields.ts';

const dist = new URL('../node_modules/@napplet/nap/dist/', import.meta.url);
const installed = JSON.parse(readFileSync(new URL('../node_modules/@napplet/nap/package.json', import.meta.url), 'utf8')).version;
if (installed !== NAP_PACKAGE_VERSION) throw new Error(`installed @napplet/nap ${installed} != NAP_PACKAGE_VERSION ${NAP_PACKAGE_VERSION}`);

const rows = [];
for (const domain of SUPPORTED_DOMAINS) {
  const authority = AUTHORITY[`nap-${domain}`];
  if (!authority) throw new Error(`no authority for ${domain}`);
  const types = new URL(`${domain}/types.d.ts`, dist);
  const pkg = parseNapTypes(readFileSync(types, 'utf8'), domain);
  const packageFields = readPackageFields(fileURLToPath(types), domain);
  const url = `https://raw.githubusercontent.com/${authority.repo}/${authority.ref}/${authority.path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  const markdown = await response.text();
  const spec = parseNapWireTable(markdown, domain);
  const specFields = parseNapWireFields(markdown, domain);
  if (!pkg.outbound.length) throw new Error(`${domain}: parsed no packaged outbound operations`);
  if (!spec.outbound.length) throw new Error(`${domain}: parsed no wire-table operations from ${url}`);
  rows.push({ domain, authority: authority.id, package: pkg, spec, packageFields, specFields });
}

const body = rows.map((row) => `  ${JSON.stringify(row.domain)}: ${JSON.stringify({ authority: row.authority, package: row.package, spec: row.spec, packageFields: row.packageFields, specFields: row.specFields })},`).join('\n');
writeFileSync(new URL('../src/catalog/inventory.generated.ts', import.meta.url), `// Generated by scripts/generate-inventory.ts from @napplet/nap@${NAP_PACKAGE_VERSION}
// and the NAP documents pinned in src/authority.ts. Do not edit by hand.
import type { DomainInventory } from './inventory.js';

/** Operations and payload fields per supported domain: packaged types and the pinned NAP wire table. */
export const INVENTORY: Readonly<Record<string, DomainInventory>> = {
${body}
};
`);
console.log(`wrote ${rows.length} domains`);
