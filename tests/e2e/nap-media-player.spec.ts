// Real PCM WAV: browser decoding, duration and currentTime are not mocked.
function wav(): Buffer {
  const rate = 8000, samples = rate * 12;
  const bytes = Buffer.alloc(44 + samples * 2);
  bytes.write('RIFF', 0); bytes.writeUInt32LE(bytes.length - 8, 4); bytes.write('WAVEfmt ', 8);
  bytes.writeUInt32LE(16, 16); bytes.writeUInt16LE(1, 20); bytes.writeUInt16LE(1, 22);
  bytes.writeUInt32LE(rate, 24); bytes.writeUInt32LE(rate * 2, 28); bytes.writeUInt16LE(2, 32); bytes.writeUInt16LE(16, 34);
  bytes.write('data', 36); bytes.writeUInt32LE(samples * 2, 40);
  for (let i = 0; i < samples; i++) bytes.writeInt16LE(Math.round(Math.sin(i * 2 * Math.PI * 220 / rate) * 400), 44 + i * 2);
  return bytes;
}

let paja: PajaServer;
let targetUrl: string;
const bytes = wav();
// Generated by ffmpeg lavfi color=0x2d6a72:s=320x180:r=12, 2s, libvpx.
const videoBytes = readFileSync(new URL('../fixtures/media/player.webm', import.meta.url));
// ffmpeg sine=frequency=220:sample_rate=44100:duration=2, mono MP3, 32k, no ID3/Xing.
const radioBytes = readFileSync(new URL('../fixtures/media/radio.mp3', import.meta.url));
let liveConnections = 0;
const server = createServer((request, response) => {
  response.setHeader('Access-Control-Allow-Origin', '*');
  if (request.url === '/live.mp3') {
    liveConnections++;
    response.setHeader('Content-Type', 'audio/mpeg');
    response.write(radioBytes);
    const interval = setInterval(() => response.write(radioBytes), 1500);
    response.once('close', () => { liveConnections--; clearInterval(interval); });
  }
  else if (request.url === '/tone.wav') { response.setHeader('Content-Type', 'audio/wav'); response.end(bytes); }
  else if (request.url === '/video.webm') { response.setHeader('Content-Type', 'video/webm'); response.end(videoBytes); }
  else { response.setHeader('Content-Type', 'text/html'); response.end('<!doctype html><html><head><title>Media test</title></head><body>Media endpoint</body></html>'); }
});

test.beforeAll(async () => {
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('missing media fixture port');
  targetUrl = `http://127.0.0.1:${address.port}`;
  paja = await startPajaServer({ options: { targetUrl, port: 0 } });
});
test.afterAll(async () => {
  await paja?.close();
  server.closeAllConnections();
  await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
});

async function exercisePlayer(page: Page, frame: Frame, url: string): Promise<void> {
  await expect.poll(() => frame.evaluate(() => typeof (window as any).napplet?.media?.onEnded)).toBe('function');
  const result = await frame.evaluate(async source => {
    const media = (window as any).napplet.media;
    const result = await media.createSession({ owner: 'shell', sessionId: 'browser-player', source: { url: source }, metadata: { title: 'Playback proof', artist: 'Kehto' }, autoplay: false });
    (window as any).mediaProof = { result, states: [], ended: [], actions: [] };
    media.onState(result.sessionId, (state: unknown) => (window as any).mediaProof.states.push(state));
    media.onCapabilities(result.sessionId, (actions: unknown) => { (window as any).mediaProof.actions = actions; });
    media.onEnded(result.sessionId, (ended: unknown) => (window as any).mediaProof.ended.push(ended));
    return result;
  }, url);
  expect(result.error).toBeUndefined();
  expect(result.owner).toBe('shell');
  const panel = page.locator('[data-kehto-media-player]');
  const row = panel.locator('article', { hasText: 'Playback proof' });
  await expect(row).toBeVisible();
  await expect(row.getByRole('slider', { name: 'Position' })).toBeEnabled();
  expect(await row.locator('audio').getAttribute('src')).toMatch(/^blob:/);
  await row.getByRole('button', { name: 'Play', exact: true }).click();
  await expect.poll(() => frame.evaluate(() => (window as any).mediaProof.states.at(-1)?.status)).toBe('playing');
  await expect.poll(() => row.locator('audio').evaluate((element: HTMLAudioElement) => element.currentTime)).toBeGreaterThan(0);
  await row.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect.poll(() => frame.evaluate(() => (window as any).mediaProof.states.at(-1)?.status)).toBe('paused');
  await frame.evaluate(() => {
    const host = window as any;
    host.napplet.media.command(host.mediaProof.result.sessionId, { action: 'volume', value: 0.6 });
  });
  await expect.poll(() => row.locator('audio').evaluate((element: HTMLAudioElement) => element.volume)).toBeCloseTo(0.6);
  await row.getByRole('slider', { name: 'Volume' }).fill('0.35');
  await expect.poll(() => row.locator('audio').evaluate((element: HTMLAudioElement) => element.volume)).toBeCloseTo(0.35);
  await row.getByRole('slider', { name: 'Position' }).fill('11.5');
  await row.getByRole('button', { name: 'Play', exact: true }).click();
  await expect.poll(() => frame.evaluate(() => (window as any).mediaProof.states.some((state: any) => state.status === 'stopped' && state.reason === 'ended'))).toBe(true);
  expect(await frame.evaluate(() => (window as any).mediaProof.ended)).toEqual([]);
  // Natural completion remains replayable, retirement does not.
  await row.getByRole('button', { name: 'Play', exact: true }).click();
  await row.getByRole('button', { name: 'Close session' }).click();
  await expect(row).toHaveCount(0);
  await expect.poll(() => frame.evaluate(() => (window as any).mediaProof.ended.length)).toBe(1);
  const late = await frame.evaluate(() => {
    const host = window as any;
    const id = host.mediaProof.result.sessionId;
    host.napplet.media.command(id, { action: 'play' });
    const ended: unknown[] = [];
    host.napplet.media.onEnded(id, (event: unknown) => ended.push(event));
    return ended;
  });
  expect(late).toEqual([{ sessionId: result.sessionId, reason: 'user' }]);
  await expect(panel).toBeHidden();
  await frame.evaluate(async () => {
    const host = window as any;
    const media = host.napplet.media;
    const session = await media.createSession({ owner: 'napplet', metadata: { title: 'Napplet player' }, capabilities: ['play', 'pause'] });
    host.nappletCommands = [];
    media.onCommand(session.sessionId, (command: any) => {
      host.nappletCommands.push(command);
      media.reportState(session.sessionId, { status: command.action === 'play' ? 'playing' : 'paused' });
    });
  });
  const nappletRow = panel.locator('article', { hasText: 'Napplet player' });
  await nappletRow.getByRole('button', { name: 'Play', exact: true }).click();
  await expect.poll(() => frame.evaluate(() => (window as any).nappletCommands)).toEqual([{ action: 'play', reason: 'user' }]);
  await expect(nappletRow.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await nappletRow.getByRole('button', { name: 'Close session' }).click();
}

